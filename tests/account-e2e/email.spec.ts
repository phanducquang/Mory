import { randomBytes, randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import pg from "pg";
import { inboxLink, openMailLink, completeVerification } from "./email-utils";
if (process.env.MORY_INTEGRATION_DATABASE !== "disposable-docker") throw new Error("Use npm run test:email.");
test.skip(process.env.AUTH_EMAIL_ENABLED !== "true", "Email account mode is opt-in.");
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL });
const password = randomBytes(24).toString("hex");
const origin = process.env.PLAYWRIGHT_BASE_URL!;
test.beforeEach(async () => { await pool.query('DELETE FROM "AuthRateLimit"'); });
test.afterAll(async () => { await pool.end(); });

test("verification requires a click; reset revokes the session, persists the new password and rejects replay", async ({ page, request }) => {
  const email = `${randomUUID()}@example.test`; const nextPassword = randomBytes(24).toString("hex");
  await page.goto("/register"); await page.getByLabel("Tên của bạn", { exact: true }).fill("Gia đình email");
  await page.getByLabel("Email", { exact: true }).fill(email); await page.getByLabel("Mật khẩu", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Tạo tài khoản", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Nếu tài khoản cần xác minh");
  const user = (await pool.query('SELECT * FROM "User" WHERE "email"=$1', [email])).rows[0];
  expect(user.emailVerified).toBe(false);
  const before = await page.request.post("/api/auth/sign-in/email", { headers: { Origin: origin }, data: { email, password } }); expect(before.status()).toBe(403);
  const verificationLink = await inboxLink(email, "VERIFY"); await openMailLink(page, verificationLink);
  await expect(page.getByRole("button", { name: "Xác minh email", exact: true })).toBeEnabled();
  expect(new URL(page.url()).hash.length === 0).toBe(true);
  expect((await pool.query('SELECT "emailVerified" FROM "User" WHERE "id"=$1', [user.id])).rows[0].emailVerified).toBe(false);
  await page.getByRole("button", { name: "Xác minh email", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Đã xác minh email");
  await page.getByRole("link", { name: "Đăng nhập", exact: true }).click();
  await page.getByLabel("Email", { exact: true }).fill(email); await page.getByLabel("Mật khẩu", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  await expect(page.getByRole("button", { name: "Tạo không gian gia đình" })).toBeVisible();
  const cookie = (await page.context().cookies()).find((c) => c.name === "mory.session_token")!;
  await page.goto("/forgot-password"); await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByRole("button", { name: "Gửi liên kết đặt lại mật khẩu", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Nếu tài khoản phù hợp tồn tại");
  const resetLink = await inboxLink(email, "RESET"); await openMailLink(page, resetLink);
  await page.getByLabel("Mật khẩu mới", { exact: true }).fill(nextPassword); await page.getByLabel("Nhập lại mật khẩu mới", { exact: true }).fill(nextPassword);
  expect(new URL(page.url()).hash.length === 0).toBe(true);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  // No screenshot of password values or token-bearing URLs is retained.
  await page.getByRole("button", { name: "Đặt lại mật khẩu", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Đã đặt lại mật khẩu");
  const revoked = await request.get("/api/auth/get-session", { headers: { cookie: `${cookie.name}=${cookie.value}` } }); expect((await revoked.json()) === null).toBe(true);
  await page.getByRole("link", { name: "Đăng nhập", exact: true }).click();
  await page.getByLabel("Email", { exact: true }).fill(email); await page.getByLabel("Mật khẩu", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Đăng nhập", exact: true }).click(); await expect(page.locator(".auth-card").getByRole("alert")).toContainText("Email hoặc mật khẩu");
  await page.getByLabel("Mật khẩu", { exact: true }).fill(nextPassword); await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  await expect(page.getByRole("button", { name: "Tạo không gian gia đình" })).toBeVisible();
  await openMailLink(page, resetLink); await page.getByLabel("Mật khẩu mới", { exact: true }).fill(nextPassword); await page.getByLabel("Nhập lại mật khẩu mới", { exact: true }).fill(nextPassword);
  await page.getByRole("button", { name: "Đặt lại mật khẩu", exact: true }).click(); await expect(page.locator(".auth-card").getByRole("alert")).toContainText("không hợp lệ hoặc đã hết hạn");
});

test("old unverified sessions are gated and recovery responses do not reveal accounts", async ({ page }) => {
  const email = `${randomUUID()}@example.test`;
  await page.goto("/register"); await page.getByLabel("Tên của bạn", { exact: true }).fill("Legacy session");
  await page.getByLabel("Email", { exact: true }).fill(email); await page.getByLabel("Mật khẩu", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Tạo tài khoản", exact: true }).click(); await completeVerification(page, email, password);
  await expect(page.getByRole("button", { name: "Tạo không gian gia đình" })).toBeVisible();
  const user = (await pool.query('SELECT "id" FROM "User" WHERE "email"=$1', [email])).rows[0];
  await pool.query('UPDATE "User" SET "emailVerified"=false WHERE "id"=$1', [user.id]);
  await page.getByRole("button", { name: "Tạo không gian gia đình" }).click(); await expect(page).toHaveURL(/\/verify-email$/);
  expect((await pool.query('SELECT count(*)::int AS n FROM "FamilyMember" WHERE "userId"=$1', [user.id])).rows[0].n).toBe(0);
  expect((await page.request.get(`/api/media/${randomUUID()}`)).status()).toBe(403);
  await page.goto("/home"); await expect(page).toHaveURL(/\/verify-email$/);
  const unknown = await page.request.post("/api/auth/request-password-reset", { headers: { Origin: origin }, data: { email: `${randomUUID()}@example.test` } });
  expect(unknown.status()).toBe(200); expect(await unknown.json()).toEqual({ status: true });
  expect((await page.request.post("/api/auth/request-password-reset", { headers: { Origin: "https://other.invalid" }, data: { email } })).status()).toBe(403);
  await page.goto("/verify-email#token=invalid-link");
  await page.getByRole("button", { name: "Xác minh email", exact: true }).click(); await expect(page.locator(".auth-card").getByRole("alert")).toBeVisible();
  expect(new URL(page.url()).hash.length === 0).toBe(true);
  const response = await page.request.get("/reset-password"); expect(response.headers()["referrer-policy"]).toBe("no-referrer");
});
