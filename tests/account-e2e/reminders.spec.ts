import { randomBytes, randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import pg from "pg";
import { completeVerification, inboxLink } from "./email-utils";
import { todayVN } from "../../src/lib/dates";
if (process.env.MORY_INTEGRATION_DATABASE !== "disposable-docker") throw new Error("Use the disposable runner.");
test.skip(process.env.MORY_REMINDERS_ENABLED !== "true", "Reminder service is opt-in.");
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL });
test.beforeEach(async () => { await pool.query('DELETE FROM "AuthRateLimit"'); });
test.afterAll(async () => { await pool.end(); });
test("a viewer can opt into their own email, receive one saved-event reminder and opt out persistently", async ({ page }) => {
  const email = `${randomUUID()}@example.test`; const password = randomBytes(24).toString("hex");
  await page.goto("/register"); await page.getByLabel("Tên của bạn", { exact: true }).fill("Nhắc lịch E2E");
  await page.getByLabel("Email", { exact: true }).fill(email); await page.getByLabel("Mật khẩu", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Tạo tài khoản", exact: true }).click(); await completeVerification(page, email, password);
  await page.getByRole("button", { name: "Tạo không gian gia đình" }).click();
  await page.getByLabel("Bé đã chào đời", { exact: true }).check(); await page.getByLabel("Tên bé", { exact: false }).fill("Bé nhận nhắc"); await page.getByLabel("Ngày sinh thực tế", { exact: false }).fill("2024-02-10");
  await page.getByRole("button", { name: "Bắt đầu hành trình", exact: true }).click(); await expect(page.getByRole("heading", { name: "Bắt đầu hành trình của con", exact: true })).not.toBeVisible();
  await page.getByRole("button", { name: "Lưu kỷ niệm mới", exact: true }).click();
  const dialog = page.getByRole("dialog"); const future = new Date(Date.now() + 3 * 3_600_000);
  await dialog.getByLabel("Tên sự kiện", { exact: false }).fill("Lịch kiểm thử riêng tư");
  await dialog.getByLabel("Ngày diễn ra", { exact: false }).fill(todayVN(future));
  await dialog.getByLabel("Giờ diễn ra", { exact: false }).fill(new Intl.DateTimeFormat("en-GB", { timeZone: "Asia/Ho_Chi_Minh", hour: "2-digit", minute: "2-digit", hourCycle: "h23" }).format(future));
  await dialog.getByLabel("Ghi nhớ nhắc nhở cho sự kiện này", { exact: true }).check();
  await dialog.getByRole("button", { name: "Lưu kỷ niệm", exact: true }).click(); await expect(dialog).not.toBeVisible();
  const user = (await pool.query('SELECT "id" FROM "User" WHERE "email"=$1', [email])).rows[0];
  await pool.query('UPDATE "FamilyMember" SET "role"=\'VIEWER\' WHERE "userId"=$1', [user.id]);
  await page.goto("/settings"); const toggle = page.getByLabel("Nhận nhắc lịch qua email của tôi", { exact: true });
  await expect(toggle).not.toBeChecked(); await toggle.check();
  await expect(page.getByText("Đã lưu lựa chọn nhắc lịch của bạn.", { exact: true })).toBeVisible();
  await page.reload(); await expect(toggle).toBeChecked();
  const link = await inboxLink(email, "REMINDER"); expect(link.includes("/events/")).toBe(true);
  await expect.poll(async () => (await pool.query('SELECT count(*)::int AS n FROM "AuthMailJob" WHERE "recipientUserId"=$1 AND "status"=\'SENT\'', [user.id])).rows[0].n).toBe(1);
  await toggle.uncheck(); await expect(page.getByText("Đã lưu lựa chọn nhắc lịch của bạn.", { exact: true })).toBeVisible(); await page.reload(); await expect(toggle).not.toBeChecked();
});
